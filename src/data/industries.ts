import { IndustryPreset, SensorThresholds } from "../types/industrial";

function makeThresholds(
  tempNominal: number,
  tempMax: number,
  vibrationNominal: number,
  vibrationMax: number,
  powerNominal: number,
  powerMax: number,
  rpmNominal: number,
  opts?: {
    pressureNominal?: number;
    pressureMax?: number;
    torqueNominal?: number;
    torqueMax?: number;
  }
): SensorThresholds {
  return {
    tempNominal,
    tempMax,
    vibrationNominal,
    vibrationMax,
    powerNominal,
    powerMax,
    rpmNominal,
    rpmVariancePct: 14,
    pressureNominal: opts?.pressureNominal,
    pressureMax: opts?.pressureMax,
    torqueNominal: opts?.torqueNominal,
    torqueMax: opts?.torqueMax,
    hasPressure: typeof opts?.pressureNominal === "number",
    hasTorque: typeof opts?.torqueNominal === "number",
  };
}

